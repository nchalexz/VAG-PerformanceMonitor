    private const val SOURCE =
        "OBDb/Audi-Q3 v3 @b51e835, UDS 22 (CC BY-SA 4.0)"

    private fun uds(
        id: String,
        nameRu: String,
        nameEn: String,
        category: SignalCategory,
        txId: Int,
        rxId: Int,
        did: Int,
        spec: UdsValueSpec,
        unit: String,
        decimals: Int,
        min: Double?,
        max: Double?,
        pollHz: Double,
    ) = SignalDefinition(
        id = id,
        nameRu = nameRu,
        nameEn = nameEn,
        category = category,
        ecu = when (txId) {
            0x7E0 -> Ecu.ENGINE
            0x7E1 -> Ecu.TRANSMISSION
            0x714 -> Ecu.CLUSTER
            0x710 -> Ecu.BODY
            else -> Ecu.UNKNOWN
        },
        protocol = Protocol.UDS,
        service = 0x22,
        did = did,
        uds = spec,
        txId = txId,
        rxId = rxId,
        unit = unit,
        decimals = decimals,
        minValue = min,
        maxValue = max,
        pollHz = pollHz,
        source = "$SOURCE, %04X".format(did),
        verification = Verification.DECODED,
        note = "Формула из открытого набора OBDb; на MQB TDI не проверялась.",
    )


package io.github.nchalexz.aaperfmon.core

import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock

/**
 * Один канал — одна транзакция.
 *
 * Телеметрия и диагностика делят физический адаптер. Без общей блокировки
 * их команды могут чередоваться внутри одной логической операции: сканер
 * блоков выставит адрес блока, а телеметрия между его запросами вернёт
 * заголовок 7DF. Блок при этом не отвечает, и скан выглядит как «нет связи».
 *
 * Поэтому любая логическая операция берёт мьютекс на всё время работы:
 * опрос одного параметра в телеметрии, поиск блоков, чтение ошибок,
 * идентификация ECU. Команды адаптера по-прежнему сериализуются
 * (`synchronized(elm)`), но теперь не смешиваются между собой.
 */
object AdapterBus {

    private val mutex = Mutex()

    suspend fun <T> transaction(block: suspend () -> T): T = mutex.withLock { block() }
}
